// Generates the admin role/permission seed SQL from the console's own PERMS table (admin/app.js),
// so the database role matrix cannot drift from what the UI exposes.
//   node supabase/tools/gen-admin-permissions.mjs > /tmp/perm_seed.sql
import { readFileSync } from 'node:fs';
import vm from 'node:vm';

const src = readFileSync(new URL('../../admin/app.js', import.meta.url), 'utf8');
const start = src.indexOf('const PERMS={');
let depth = 0, end = start + 'const PERMS='.length;
for (let i = end; i < src.length; i++) {
  if (src[i] === '{') depth++;
  if (src[i] === '}' && --depth === 0) { end = i + 1; break; }
}
const PERMS = vm.runInNewContext('(' + src.slice(start + 'const PERMS='.length, end) + ')');

// Permissions referenced by modules but not (yet) granted to a non-super role, plus governance permissions.
const extra = ['roles.manage', 'locations.manage', 'system.operations.manage', 'system.capacity.view', 'system.incidents.view',
  'system.recovery.view', 'verification.suspend', 'analytics.definitions.manage', 'analytics.financial.view', 'audit.export',
  'privacy.requests.view', 'privacy.requests.assign', 'privacy.requests.review', 'privacy.requests.decide', 'privacy.requests.complete',
  'catalogue.import', 'catalogue.import.validate', 'catalogue.import.commit', 'catalogue.import.history.view', 'revenue.view',
  'payments.reconcile', 'payments.evidence.view', 'payments.export', 'quotes.investigate', 'orders.investigate', 'rfqs.investigate'];
const all = new Set(extra);
for (const r of Object.values(PERMS)) (r.perms || []).forEach(p => all.add(p));
for (const m of src.matchAll(/perms:\[([^\]]*)\]/g)) for (const p of m[1].matchAll(/"([a-z][a-z.]+)"/g)) all.add(p[1]);
for (const m of src.matchAll(/\bperm:"([a-z][a-z.]+)"/g)) if (m[1] !== 'search.any') all.add(m[1]);

const q = s => "'" + String(s).replace(/'/g, "''") + "'";
const out = [];
out.push('-- GENERATED by supabase/tools/gen-admin-permissions.mjs from admin/app.js — do not edit by hand.');
out.push('insert into public.admin_permissions (code) values');
out.push([...all].sort().map(p => `  (${q(p)})`).join(',\n') + '\non conflict do nothing;\n');
out.push('insert into public.admin_roles (code, label, all_permissions) values');
out.push(Object.entries(PERMS).map(([k, r]) => `  (${q(k)}, ${q(r.label)}, ${r.all ? 'true' : 'false'})`).join(',\n') + '\non conflict do nothing;\n');
const rp = [];
for (const [k, r] of Object.entries(PERMS)) for (const p of r.perms || []) rp.push(`  (${q(k)}, ${q(p)})`);
out.push('insert into public.admin_role_permissions (role_code, permission_code) values');
out.push(rp.join(',\n') + '\non conflict do nothing;\n');
const sc = [];
for (const [k, r] of Object.entries(PERMS)) for (const c of r.scope || []) sc.push(`  (${q(k)}, ${q(c)})`);
out.push('insert into public.admin_role_scopes (role_code, category_id) values');
out.push(sc.join(',\n') + '\non conflict do nothing;');
console.log(out.join('\n'));
